import type { LevelDef, PowerDef, Rect, TrafficDef } from "./types";

const GY = 500;
const GH = 240;

function gnd(x: number, w: number, y = GY): Rect {
  return { x, y, w, h: GH };
}
function plat(x: number, y: number, w: number, h = 22): Rect {
  return { x, y, w, h };
}
function cone(x: number, y = GY): LevelDef["hazards"][number] {
  return { kind: "cone", x, y: y - 28, w: 24, h: 28 };
}
function oil(x: number, y = GY): LevelDef["hazards"][number] {
  return { kind: "oil", x, y: y - 14, w: 64, h: 14 };
}
function spikes(x: number, y = GY, w = 56): LevelDef["hazards"][number] {
  return { kind: "spikes", x, y: y - 18, w, h: 18 };
}
function xy(x: number, y: number) {
  return { x, y };
}
function p(x: number, y: number, kind: PowerDef["kind"]): PowerDef {
  return { x, y, kind };
}
function traf(
  x: number,
  min: number,
  max: number,
  vx: number,
  kind: TrafficDef["kind"],
  ride = true,
): TrafficDef {
  return { x, min, max, vx, kind, ride };
}

